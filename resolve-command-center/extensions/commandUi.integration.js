const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { _electron: electron } = require('playwright');

test('isolated real Electron: static inputs, cancellation, running, result, notification, errors, native focus and edges', { timeout: 180000 }, async (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'clackly-command-ui-'));
  const evidence = path.resolve(__dirname, '../build/issue7/electron'); fs.mkdirSync(evidence, { recursive: true });
  const archive = path.join(root, 'summary.clackly');
  execFileSync('python', [path.resolve(__dirname, '../../skills/clackly-developer/scripts/package_extension.py'),
    path.resolve(__dirname, '../../skills/clackly-developer/examples/run-summary'), archive], { windowsHide: true });
  const env = { ...process.env, CLACKLY_UI_TEST_ROOT: root, CLACKLY_UI_TEST_PACKAGE: archive };
  delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ args: [path.join(__dirname, 'commandUi-electron-fixture.js')], env });
  app.process().stderr.on('data', (data) => process.stderr.write(data));
  const errors = [];
  try {
    const palette = await app.firstWindow(); palette.on('pageerror', (error) => errors.push(error.message));
    await palette.waitForFunction(() => !!window.resolveCommandCenter);
    await app.evaluate(() => new Promise((resolve) => { const check = () => global.commandUiTest ? resolve() : setTimeout(check, 25); check(); }));
    const count = () => app.evaluate(() => global.commandUiTest.requests.length);
    const start = async (id) => palette.evaluate((id) => window.resolveCommandCenter.executeCommand(id), id);
    const open = async (id) => {
      const next = app.waitForEvent('window'); await start(id); const page = await next;
      page.on('pageerror', (error) => errors.push(error.message));
      await page.locator('h1').waitFor(); return page;
    };
    const close = async (page) => {
      const closed = page.waitForEvent('close');
      await page.keyboard.press('Escape').catch((error) => { if (!page.isClosed()) throw error; });
      await closed;
    };
    const summary = 'extension:clackly.demo.run-summary/summary';
    const initialCount = await count();
    let page = await open(summary);
    await page.locator('#setting-title').waitFor();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'setting-title');
    await page.keyboard.press('Tab'); assert.equal(await page.evaluate(() => document.activeElement.id), 'setting-notes');
    await page.screenshot({ path: path.join(evidence, 'input-en.png') });
    await page.getByRole('button', { name: 'Run command', exact: true }).click();
    assert.equal(await count(), initialCount);
    await page.locator('#setting-title').fill('One run only');
    await page.getByLabel('备注', { exact: true }).fill('Two\nlines');
    await page.getByRole('button', { name: 'Run command', exact: true }).click();
    assert.equal(await count(), initialCount);
    // Native OS picker is deliberately not automated: type paths and verify transport.
    await page.getByLabel('可选文件', { exact: true }).fill('C:/input.txt');
    await page.getByLabel('可选文件夹', { exact: true }).fill('C:/output');
    await page.getByLabel('格式', { exact: true }).selectOption('详细');
    await page.getByLabel('颜色', { exact: true }).fill('#112233');
    await page.getByRole('switch').uncheck();
    await close(page); assert.equal(await count(), initialCount);
    assert.equal(await app.evaluate(() => global.commandUiTest.palette.isFocused()), true);
    page = await open(summary);
    assert.equal(await page.locator('#setting-title').inputValue(), '');
    await page.locator('#setting-title').fill('<script>literal title</script>');
    await page.getByLabel('备注', { exact: true }).fill('Long result\n'.repeat(100));
    await page.getByLabel('数字一', { exact: false }).fill('1.5');
    await page.getByRole('switch').uncheck();
    await page.getByLabel('格式', { exact: true }).selectOption('详细');
    await page.getByLabel('颜色', { exact: true }).fill('#112233');
    await page.getByLabel('可选文件', { exact: true }).fill('C:/input.txt');
    await page.getByLabel('可选文件夹', { exact: true }).fill('C:/output');
    await page.locator('.command-confirm input').check();
    await page.getByRole('button', { name: 'Run command', exact: true }).click();
    await page.getByRole('heading', { name: '本次摘要已生成' }).waitFor();
    await page.screenshot({ path: path.join(evidence, 'result-en.png') });
    assert.equal(await count(), initialCount + 1);
    const input = await app.evaluate(() => global.commandUiTest.requests.at(-1).input);
    assert.equal(input.number_one, 1.5); assert.equal(input.include_tags, false); assert.equal(input.format, '详细');
    assert.equal(input.color, '#112233'); assert.equal(input.file, 'C:/input.txt'); assert.equal(input.folder, 'C:/output');
    assert.equal(await page.locator('.command-result script').count(), 0);
    assert.equal(await page.locator('.command-content').evaluate((node) => node.scrollHeight > node.clientHeight), true);
    await page.getByRole('button', { name: 'Copy result' }).click();
    await page.getByText('Copied', { exact: true }).waitFor();
    assert.match(await app.evaluate(() => global.commandUiTest.clipboard.readText()), /literal title/);
    assert.deepEqual(await app.evaluate(() => global.commandUiTest.core.extensions.list().find((item) => item.id === 'clackly.demo.run-summary').values), { prefix: 'Saved prefix' });
    await page.locator('.command-content').evaluate((node) => { node.scrollTop = node.scrollHeight; });
    await page.screenshot({ path: path.join(evidence, 'result-details.png') });
    await close(page);
    page = await open('extension:test.command-ui/input');
    await page.locator('#setting-count').fill('9');
    await page.getByRole('button', { name: 'Run command', exact: true }).click();
    assert.equal(await count(), initialCount + 1);
    await page.locator('#setting-count').fill('2');
    await page.locator('#setting-count').press('Enter');
    await page.getByRole('heading', { name: 'Running…', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Cancel', exact: true }).count(), 0);
    await page.screenshot({ path: path.join(evidence, 'running-en.png') });
    await page.keyboard.press('Escape');
    assert.equal(await app.evaluate(() => { const window = global.commandUiTest.windows.at(-1); window.close(); return window.isDestroyed(); }), false);
    await start('extension:test.command-ui/input');
    await page.getByRole('heading', { name: 'Input accepted' }).waitFor();
    assert.equal(await count(), initialCount + 2);
    await close(page);
    page = await open('extension:test.command-ui/confirm');
    await close(page); assert.equal(await count(), initialCount + 2);
    const legacyWindows = app.windows().length;
    await start('extension:test.command-ui/legacy'); assert.equal(app.windows().length, legacyWindows);
    page = await open('extension:clackly.demo.run-summary/details');
    await page.getByRole('heading', { name: '结构化详情已准备' }).waitFor(); await close(page);
    const notificationPage = app.waitForEvent('window');
    await start('extension:clackly.demo.run-summary/notice');
    const notification = await notificationPage;
    await notification.getByRole('status').filter({ hasText: '操作成功' }).waitFor();
    await notification.screenshot({ path: path.join(evidence, 'notification.png') });
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((window) => window.webContents.getURL().includes('command-notification')).isFocusable()), false);
    await notification.waitForEvent('close');
    for (const id of ['multiline', 'long-message']) {
      page = await open('extension:test.command-ui/' + id);
      await page.locator('.command-result').waitFor();
      await page.setViewportSize({ width: 320, height: 480 });
      assert.equal(await page.getByRole('button', { name: 'Copy result' }).isVisible(), true);
      await page.getByRole('button', { name: 'Copy result' }).click();
      await page.getByText('Copied', { exact: true }).waitFor();
      assert.match(await app.evaluate(() => global.commandUiTest.clipboard.readText()), id === 'multiline' ? /Line one\nLine one/ : /Readable result/);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
      await page.screenshot({ path: path.join(evidence, id + '-320.png') });
      await close(page);
    }
    for (const id of ['error', 'business', 'malformed', 'timeout']) {
      page = await open('extension:test.command-ui/' + id);
      await page.locator('.command-failure').waitFor();
      await page.getByText('Technical details', { exact: true }).click();
      assert.ok((await page.locator('.command-result pre').innerText()).length > 0);
      await page.screenshot({ path: path.join(evidence, id + '.png') });
      if (id === 'timeout') assert.match(await page.locator('.command-failure').innerText(), /timed out/);
      await close(page);
    }
    await app.evaluate(() => global.commandUiTest.core.localizationService.setLocalePreference('zh-CN'));
    page = await open(summary);
    await page.getByRole('button', { name: '运行命令', exact: true }).waitFor();
    await page.screenshot({ path: path.join(evidence, 'input-zh.png') });
    const bounds = await app.evaluate(({ screen }) => {
      const window = global.commandUiTest.windows.filter((window) => !window.isDestroyed()).at(-1);
      const bounds = window.getBounds(); const area = screen.getDisplayMatching(bounds).workArea;
      return { bounds, area, focused: window.isFocused(), topmost: window.isAlwaysOnTop() };
    });
    assert.ok(bounds.focused && bounds.topmost);
    assert.ok(bounds.bounds.x >= bounds.area.x && bounds.bounds.y >= bounds.area.y);
    assert.ok(bounds.bounds.x + bounds.bounds.width <= bounds.area.x + bounds.area.width);
    assert.ok(bounds.bounds.y + bounds.bounds.height <= bounds.area.y + bounds.area.height);
    await page.setViewportSize({ width: 320, height: 480 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: path.join(evidence, 'input-320.png') });
    await close(page);
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(evidence, 'receipt.json'), JSON.stringify({ environment: 'Real Electron with isolated Core/filesystem/local Python; no Resolve; native picker not exercised', bounds, checks: 'All assertions passed', requests: await count(), errors }, null, 2));
  } finally { await app.close(); fs.rmSync(root, { recursive: true, force: true }); }
});
